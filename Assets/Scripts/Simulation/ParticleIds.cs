namespace TapTap2026.Simulation
{
    /// <summary>
    /// 类型 id 的跨类型引用入口。禁止在热路径写裸数字 typeId，一律用这里的字段。
    /// 字段由 <see cref="ParticleRegistration.RegisterAll"/> 在注册时回填。
    /// </summary>
    /// <remarks>
    /// 注册顺序 = id = 存档兼容性的一部分。一旦有存档或回放，**禁止重排已有顺序**，只能追加。
    /// </remarks>
    public static class ParticleIds
    {
        /// <summary>空气。恒为 0。</summary>
        public const ushort Air = ParticleRegistry.AirTypeId;

        // ================= 新增类型在此追加字段（只能追加，不能插队） =================

        /// <summary>石头。受重力的固体，摩擦度 0.9 + 高粘性 0.9（靠着石头时外侧几乎不滚，垛得很高）。</summary>
        public static ushort Stone;

        /// <summary>沙。受重力的粉末，摩擦度 0（1:1 安息角，45°）。</summary>
        public static ushort Sand;

        /// <summary>土壤。受重力的粉末，摩擦度 0.5 + 粘性 0.5（旁边有固体时约 3:1 的安息角）。</summary>
        public static ushort Soil;

        /// <summary>水。受重力的液体（Liquid 标签）：下落 → 斜滑 → 横流摊平，无安息角；被固体沉穿
        /// （**下落的固体在运动中**；静止的固体推不动水——见 `ParticleRules.CanDisplace` 的地下水闸门）。
        /// 受热蒸发成水汽（进入湿度场），是湿度场唯一的水汽来源。随机刻命中且半径 2 格内有土壤/湿土/腐殖土时，
        /// 以 20% 概率把其中第一个冲刷成沙。</summary>
        public static ushort Water;

        /// <summary>大气。气体：空气粒子化，浮力 + 热压流的载体（海陆风），也是云的载体（含凝结物的空气）。字段不叫 Air——Air 已被 typeId 0（空）占用。</summary>
        public static ushort Atmosphere;

        /// <summary>湿土。土吸水后的形态（固体标签）：堆形与干土一致，颜色更深，比干土更重、更扛热、导热更好。
        /// 由 <c>SoilParticle</c> 在正上方是水（吸干那格水）时生成，自身负责把这份水交给邻格的干土或蒸发进空气。
        /// **只能追加到清单末尾**。</summary>
        public static ushort WetSoil;

        /// <summary>草种子。受重力的固体粉末（摩擦/粘性 0.5，堆形与土一致）：随机刻命中且八邻有湿土时，
        /// 把自己与上方 1-3 格（随机高度）替换成草；连续 3 次命中都无发芽条件则霉烂成腐殖质
        /// （计数存在本格 flags 的 bit5-6）。不可在编辑器中按半径刷，只能单颗投放（见 ParticleEditor 白名单）。</summary>
        public static ushort GrassSeed;

        /// <summary>草。固体（靠空的 OnMotion 保持不动，而非 IsStatic——静态类型收不到随机刻）：
        /// 由草种子生长生成。**逻辑帧**里**衰老**——每逻辑帧年龄 +1（年龄 = shade × 10 + flags bit3-6），
        /// shade 每 10 帧推进一档、颜色由年轻绿渐变到老黄绿，年龄到 2400 逻辑帧即寿终；
        /// **随机刻**里按顺序做五件事：被上方固/液（非草）压死（死亡向下传播）、
        /// 失去扎根（下方非土/湿土/腐殖土）而死（死亡向上传播）、温度 &gt; 50 或 &lt; 3 时死亡、
        /// 15% 概率在半径 2 格内撒下一颗新草种子、把半径 2 格内的第一个沙变成土。不可在编辑器中选择。</summary>
        public static ushort Grass;

        /// <summary>腐殖质。有机物（带 Organic 标签）死亡时以 20% 概率就地生成；固体、短暂中间态——
        /// 每逻辑帧尝试把八邻的第一个土壤变成腐殖土，然后自己消失。不可在编辑器中选择。</summary>
        public static ushort Humus;

        /// <summary>腐殖土。土壤被腐殖质改良后的黑色形态；固体，与干土同款粉末运动（摩擦 / 粘性 0.5）。
        /// **逻辑帧无变化**（`hasLogic: false`）；**随机刻**里被点到、且**正上方一格是腐殖质**时，
        /// 从近到远找邻近第一个普通 / 湿润土壤，把它改良成腐殖土 / 湿润腐殖土（普通土壤 → 腐殖土、
        /// 湿润土壤 → 湿润腐殖土），并把上方那格腐殖质吸收掉（`Clear`）——腐殖土因此向外扩张。
        /// 附近没有土壤则什么都不做，腐殖质留在原地等下一次随机刻（本类型不摇骰；唯一的随机流消耗是
        /// 换形态时世界对 `shade` 的抽样）。不可在编辑器中选择。</summary>
        public static ushort HumusSoil;

        /// <summary>水生态种子。受重力的固体粉末（摩擦/粘性 0.5）：沉到水底基质上后，随机刻命中且
        /// 「正上方是水 + 正下方是软底」时**吸收头顶那格水**、自身发芽成 1 格水生植物（长高由植物自己逐格驱动）；
        /// 连续 3 次无发芽条件则霉烂成腐殖质（计数存在本格 flags 的 bit5-6，与草种子共用）。
        /// 不带 Organic 标签（否则发芽 SetPhase 种子→植物 会被 20% 腐殖质衰变截胡；腐殖质只来自显式霉烂）。
        /// 可由 <c>ParticleEditor</c> 单颗投放。<b>只能追加到清单末尾</b>。</summary>
        public static ushort AquaticSeed;

        /// <summary>水生植物。沉水、扎根水底（固体，靠空的 OnMotion 定植而非 IsStatic——静态类型收不到随机刻）。
        /// **每格植物 ⇔ 一格水**：诞生时消耗一格水、死亡时原样归还（1:1，水守恒由构造保证，无需任何标记）。
        /// **逻辑帧 = 衰老**：年龄 = `Cell.shade` × `TicksPerShadeStep`(5) + flags bit3-5 的余数
        /// （与草共用 <c>CellFlags.GrassAgeRemainderMask</c>），每 5 帧把 `shade` 推进一档
        /// （`shade` 即颜色档，调色板由深绿渐变到黄绿 ⇒ 越老越黄），年龄到 `LifespanTicks`（1200 ≈ 60 秒）
        /// 即寿终——`SetPhase` 还成水（植物不带 Organic，不留腐殖质）。
        /// **随机刻**里按顺序：被上方固体（非同类）压死（向下整段还水）、失去扎根（向下整段还水）、
        /// 八邻无液体时脱水死（单格还水）、温度 &gt; 50 或 &lt; 0 死（单格还水）、
        /// 生长（头顶是水且上方还有一格水时消耗头顶那格长高一格，株高 ≤ MaxPlantHeight=3）、
        /// 10% 概率撒种（找「软底 + 正上方是水 + 水柱顶上有接收格」的列：水位 +1，水格变成种子——基质不消耗）。
        /// 被覆盖（固体压埋）时那份水注入八邻气体格的湿度场（水汽，仍计入水账）。
        /// 不带 Organic 标签（物质归水，不留腐殖质）。不可在编辑器中选择。<b>只能追加到清单末尾</b>。</summary>
        public static ushort AquaticPlant;

        /// <summary>火焰。气体：接触点燃邻接的草（八邻固定序，每逻辑帧 1/20 概率；有草且不贴淬熄物时不摇熄灭骰）、
        /// 接触烤干邻接湿土（水汽走湿度场守恒）、贴石头 / 沙 / 水 / 湿土时快熄骰 1/20（非草木实体速灭；
        /// 干土与腐殖类不参与淬熄）、**正下方**是石头 / 沙 / 水（被压顶）当帧直接熄灭、
        /// 失去附着物每运动帧下沉一格且每逻辑帧 1/5 立即熄灭（火焰不算附着物）、
        /// 托着无燃料 1/120 自然熄灭；每逻辑帧向本格注入热量抬升周围温度（格温低于 400 度才注入，
        /// 烤热贴着的沙 / 石）、shade 每逻辑帧随机游走＝视觉跳动（不消耗随机流）。
        /// 投放资格 CanPlaceAt：只在空气 / 气体格（不覆盖实体），**无附着 / 悬空限制**。
        /// 被水 / 沙置换即灭（世界规则涌现）。
        /// 可在编辑器手刷（ParticleEditor 的 Gas 白名单 _placeableGasTypes 默认放行火）。
        /// **只能追加到清单末尾**。</summary>
        public static ushort Fire;

        /// <summary>树木种子。受重力的固体粉末：随机刻命中且「落土（三土之一）+ 物种基质档」满足时，
        /// 按物种概率发芽成树干——松/柏耐旱（任意土即可）、杨/橡喜湿（还需八邻有湿土）、
        /// 柳最喜水（正下方必须恰为湿土）；比草种子的「命中即发」明显更慢（1/D 概率）。
        /// flags 私有位：bit3-5 = 物种、bit6-7 = 打击计数（3 次无发芽条件霉烂成腐殖质）。
        /// 可由编辑器单颗投放（ParticleEditor 白名单），树种用 Shift+滚轮切换。
        /// **只能追加到清单末尾**。</summary>
        public static ushort TreeSeed;

        /// <summary>树干。固体 + Organic，靠空的 OnMotion 定植（非 IsStatic——静态类型收不到 OnLogic）。
        /// 由树木种子发芽生成；**每逻辑帧**：逐格判定死亡（失去扎根即整段级联倒下、温度 &gt; 50 死），
        /// 顶格负责生长（按物种 H 向上爬升，再按有序偏移表造冠——被固液挡住的表项跳过、全表填满转成熟，
        /// 成熟后零随机流消耗）。flags 私有位：bit3-5 = 物种、bit6-7 = 生长阶段（0/1/2）。不可在编辑器中选择。
        /// **只能追加到清单末尾**。</summary>
        public static ushort TreeTrunk;

        /// <summary>树叶。固体 + Organic。**随机刻**里：已失活则 Clear（只在「再被随机刻点到」时才死）；
        /// 否则 ① 温度 &gt; 50（低温致死 0）、② 正上方被固体（非树叶）压、③ 支撑半径内没有树干——
        /// 整树倒下后树叶**不立即死**，而是记录失活（flags bit6）并立刻让八邻一圈的树叶各自检测支撑
        /// （无支撑者同样失活、继续扩散 → 整冠一瞬间集体失活），失活叶在 `OnMotion` 里**竖直自由下落**
        /// （不滚落，正下方是固体就停），落稳后等自己的随机刻收尸。死亡走 Clear，按世界 20% 有机衰变
        /// 留腐殖质（落叶归根）。flags 私有位：bit3-5 = 物种、bit6 = 失活标记。
        /// 不可在编辑器中选择。**只能追加到清单末尾**。</summary>
        public static ushort TreeLeaf;

        /// <summary>花。**草株顶端的显色格**：由草种子发芽时以 30%（3/10）概率把株顶那格草换来的（见
        /// <c>GrassSeedParticle.OnRandomTick</c>）。继承草的全部性质（Solid + Organic、长在原地、
        /// 热学与光照同值、随机刻三条死法：被压 / 失去扎根 / 温度 &gt; 50 或 &lt; 3，死亡各按 20% 留腐殖质），
        /// 差别只有颜色与两项刻意去掉的行为：**不衰老**（shade 是花色而不是年龄档，没有寿命；OnLogic 是严格空体）、
        /// **不撒种 / 不固沙**。花色 = 调色板随机下标（更鲜艳、每朵随机、终生不变），不占用 flags 私有位。
        /// 与草互为「同一株」：互不算压、互为扎根、级联死亡一起清。不可在编辑器中选择。
        /// **只能追加到清单末尾**。</summary>
        public static ushort Flower;

        /// <summary>湿润腐殖土。腐殖土 + 一份水的形态（固体标签）：由 <see cref="HumusSoilParticle.OnRandomTick"/>
        /// 把邻近的**湿润土壤**改良成它时产生（水原样带进湿润形态，水账不失）。**逻辑与湿土逐条同构**——
        /// 受热上行（T ≥ 60 蒸发 / 润湿上方干腐殖土）、常温有压才渗（把水交给邻格干腐殖土，正下方优先、
        /// 被挡随机序试左右）、孤立永久持水；水迁移时带 T(源)×1.2 的热一起走、两侧温度不跳。
        /// 不可在编辑器中选择。**只能追加到清单末尾**。</summary>
        public static ushort WetHumusSoil;

        /// <summary>雷电。气体（密度 1.0 —— 最重的气体，环境大气推不动它），**不可手刷**：
        /// 只能由「随机刻命中空气粒子」起爆——<see cref="LightningParticle.TryStrike"/> 先摇 2% 门、
        /// 再要求半径 3 圆盘（29 格）总湿度 ≥ 3.0（厚雨云），然后把自本格向下的一整条主干铺成雷电
        /// （逐行按坐标哈希 ±1 抖动、遇固 / 液即止 = 落点），并在落点上方那排创建一团火
        /// （<see cref="ParticleIds.Fire"/>）。`Cell.shade` 即闪光档（0 = 最亮），每逻辑帧推进一档、
        /// 末档（<see cref="LightningParticle.LifetimeTicks"/> = 4 ≈ 0.2 秒）即 Clear——**不占用任何 flags 私有位**。
        /// 热学参数与大气同值（不注热 / 不挡光），放电的热效应由落点那团火负责。
        /// **只能追加到清单末尾**。</summary>
        public static ushort Lightning;
    }
}
